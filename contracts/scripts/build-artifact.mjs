import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";
import { keccak256 } from "viem";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const contractsDir = resolve(scriptDir, "..");
const rootDir = resolve(contractsDir, "..");
const sourceFile = resolve(contractsDir, "src/WifPermit2SessionMandate.sol");
const source = readFileSync(sourceFile, "utf8");
const input = {
  language: "Solidity",
  sources: { "src/WifPermit2SessionMandate.sol": { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "shanghai",
    metadata: { bytecodeHash: "none" },
    outputSelection: {
      "*": {
        WifPermit2SessionMandate: [
          "abi",
          "evm.bytecode.object",
          "evm.deployedBytecode.object",
          "evm.deployedBytecode.immutableReferences",
        ],
      },
    },
  },
};
const compiled = spawnSync("npx", ["--yes", "solc@0.8.30", "--standard-json"], {
  shell: process.platform === "win32",
  cwd: contractsDir,
  input: JSON.stringify(input),
  encoding: "utf8",
  maxBuffer: 16 * 1024 * 1024,
});
if (compiled.status !== 0) {
  throw new Error(`solc failed (exit ${compiled.status ?? "unknown"})\n${compiled.stderr}\n${compiled.stdout}`);
}
const jsonStart = compiled.stdout.indexOf("{");
if (jsonStart < 0) throw new Error(`solc returned no JSON output\n${compiled.stdout}\n${compiled.stderr}`);
const output = JSON.parse(compiled.stdout.slice(jsonStart));
const errors = (output.errors ?? []).filter((error) => error.severity === "error");
if (errors.length) throw new Error(`Solidity errors:\n${JSON.stringify(errors, null, 2)}`);
const contract = output.contracts?.["src/WifPermit2SessionMandate.sol"]?.WifPermit2SessionMandate;
if (!contract) throw new Error("solc did not return WifPermit2SessionMandate.");

const bytecode = `0x${contract.evm.bytecode.object}`;
const deployedBytecode = `0x${contract.evm.deployedBytecode.object}`;
const immutableReferences = contract.evm.deployedBytecode.immutableReferences ?? {};
if (!/^0x[0-9a-f]+$/i.test(bytecode) || !/^0x[0-9a-f]+$/i.test(deployedBytecode)) {
  throw new Error("solc emitted unresolved links or non-hex bytecode; refusing to write a deployable artifact.");
}
let normalizedRuntime = deployedBytecode.slice(2).toLowerCase();
for (const references of Object.values(immutableReferences)) {
  for (const { start, length } of references) {
    const begin = start * 2;
    const end = begin + length * 2;
    normalizedRuntime = `${normalizedRuntime.slice(0, begin)}${"0".repeat(length * 2)}${normalizedRuntime.slice(end)}`;
  }
}
const runtimeTemplate = `0x${normalizedRuntime}`;
const artifact = {
  contractName: "WifPermit2SessionMandate",
  sourceSha256: createHash("sha256").update(source).digest("hex"),
  compiler: "solc 0.8.30",
  settings: input.settings,
  abi: contract.abi,
  bytecode,
  deployedBytecode,
  immutableReferences,
  runtimeTemplate,
  runtimeTemplateHash: keccak256(runtimeTemplate),
};
const outPath = resolve(rootDir, "sdk/js/src/wif-mandate-artifact.ts");
writeFileSync(
  outPath,
  `// Generated by contracts/scripts/build-artifact.mjs. Do not edit by hand.\nexport const WIF_MANDATE_ARTIFACT = ${JSON.stringify(artifact, null, 2)} as const;\n`,
);
const runtimeMetadata = {
  runtimeTemplateHash: artifact.runtimeTemplateHash,
  byteLength: (deployedBytecode.length - 2) / 2,
  immutableReferences: Object.values(immutableReferences).flat(),
  abi: contract.abi.filter(item => item.type === "function" && item.stateMutability === "view" && item.inputs.length === 0),
};
writeFileSync(resolve(rootDir, "src/payments/wif-mandate-runtime.ts"), `// Generated by contracts/scripts/build-artifact.mjs.\nexport const WIF_MANDATE_RUNTIME = ${JSON.stringify(runtimeMetadata, null, 2)} as const;\n`);
console.log(`Wrote ${outPath}`);
console.log(`source sha256: ${artifact.sourceSha256}`);
console.log(`creation bytecode: ${(bytecode.length - 2) / 2} bytes`);
console.log(`runtime bytecode: ${(deployedBytecode.length - 2) / 2} bytes`);
console.log(`normalized runtime hash: ${artifact.runtimeTemplateHash}`);
